/**
 * The database is the source of truth; Asterisk config is generated, never
 * hand-edited. One `apply` produces a full, deterministic configuration, so a
 * broken file is always one click away from correct.
 */

const safe = (value, fallback = '') =>
  String(value ?? '')
    .replace(/[^A-Za-z0-9_.-]/g, '')
    .slice(0, 64) || fallback;

const plain = (value) => String(value ?? '').replace(/[\r\n"]/g, ' ').slice(0, 80);
const sectionName = (prefix, value) => `${prefix}-${safe(value, 'x')}`;
/** SIP domain for From/To headers: never the container's hex hostname. */
const sipDomain = () => safe(config.telephony.sipDomain, 'localhost');

export function generateConfigs() {
  const extensions = db_.all('SELECT * FROM extensions WHERE enabled = 1 ORDER BY extension');
  const trunks = db_.all('SELECT * FROM trunks WHERE enabled = 1 ORDER BY name');
  const flows = db_.all('SELECT * FROM ivr_flows WHERE enabled = 1 ORDER BY extension');
  const dids = db_.all(
    `SELECT n.id AS number_id, n.e164, n.fax_mode, e.extension, e.display_name
       FROM numbers n
       JOIN extensions e ON e.number_id = n.id
      WHERE e.enabled = 1`
  );
  // A number marked as a fax line does not need an extension to be reachable:
  // the switch answers it, so a fax-only DID is a real destination on its own.
  if (config.fax.enabled) {
    dids.push(
      ...db_.all(
        `SELECT n.id AS number_id, n.e164, n.fax_mode, '' AS extension, '' AS display_name
           FROM numbers n
          WHERE n.fax_mode = 'fax'
            AND n.id NOT IN (SELECT number_id FROM extensions WHERE number_id IS NOT NULL)`
      )
    );
  }
  // Active voice agents own a recording policy for the number they answer: the
  // switch has to know it, because only the dialplan can start MixMonitor.
  const agents = db_.all(
    `SELECT name, number_id, record_inbound, record_outbound
       FROM voice_agents
      WHERE status = 'active' AND number_id IS NOT NULL`
  );
  const policy = new Map(agents.map((agent) => [agent.number_id, agent]));
  // A line with a registered phone is a line worth parking a call for: there is
  // a device for the push to wake, and the app needs a slot to dial.
  const parkedLines = new Set(
    config.parking.enabled && config.apns.enabled && config.apns.ringOnDial
      ? db_.all('SELECT DISTINCT extension FROM push_devices').map((row) => String(row.extension))
      : []
  );
  const tls = tlsPaths();

  return {
    'pjsip.conf': pjsip(extensions, trunks, tls),
    'extensions.conf': dialplan(extensions, trunks, flows, dids, policy, parkedLines),
    'voicemail.conf': voicemail(extensions),
    'res_parking.conf': parking(),
    'manager.conf': manager(),
    'http.conf': http(tls),
    'rtp.conf': rtp(),
    // The fax engine's own settings. T.38 is preferred and G.711 passthrough is
    // the fallback, which is what makes a fax work over a plain SIP trunk with
    // no carrier fax service and no per-page charge.
    ...(config.fax.enabled ? { 'res_fax.conf': faxConf() } : {}),
  };
}

/**
 * The address clients reach this switch on. Explicit config wins; otherwise the
 * public URL's host, as long as it is not loopback (a laptop needs no NAT hint).
 */
export function externalAddress() {
  if (config.telephony.externalAddress) return config.telephony.externalAddress;
  try {
    const host = new URL(config.publicUrl).hostname;
    return ['localhost', '127.0.0.1', '::1'].includes(host) ? '' : host;
  } catch {
    return '';
  }
}

/**
 * Where the switch's TLS material lives. Generated on first apply, or supplied
 * with SOFTPHONE_TLS_CERT / SOFTPHONE_TLS_KEY when a real certificate exists.
 */
export function tlsPaths() {
  // In the container the switch reads /etc/asterisk; without a switch (dev on a
  // laptop) the same material lives on the data volume so previews are real.
  const dir = config.telephony.configDir || config.dataDir;
  const cert = config.softphone.tlsCert || (dir ? join(dir, 'keys', 'telno.crt') : '');
  const key = config.softphone.tlsKey || (dir ? join(dir, 'keys', 'telno.key') : '');
  return { cert, key, ready: !!(cert && key && existsSync(cert) && existsSync(key)) };
}

function pjsip(extensions, trunks, tls = tlsPaths()) {
  const out = [
    '; generated by telno — do not edit, changes are overwritten on apply',
    '',
    '[global]',
    'type=global',
    'user_agent=Telno',
    '',
    '[transport-udp]',
    'type=transport',
    'protocol=udp',
    'bind=0.0.0.0:5060',
    'allow_reload=yes',
    '',
  ];

  // The browser softphone registers over secure WebSocket, so chan_pjsip needs a
  // WSS listener of its own. This is the whole media gateway: Asterisk terminates
  // DTLS-SRTP, and the platform never touches RTP.
  if (tls.cert && tls.key) {
    const external = externalAddress();
    out.push(
      ';[softphone] secure WebSocket transport — DTLS is negotiated per media stream',
      '[transport-wss]',
      'type=transport',
      'protocol=wss',
      `bind=0.0.0.0:${config.softphone.wssPort}`,
      `cert_file=${tls.cert}`,
      `priv_key_file=${tls.key}`,
      'allow_reload=yes',
      // Behind Docker's bridge (or any NAT) the container address is useless to
      // the browser: advertise the address it actually reaches, and tell ICE
      // which ranges are local so it does not waste candidates on them.
      external ? `external_signaling_address=${external}` : '',
      external ? `external_media_address=${external}` : '',
      ...config.telephony.localNets.map((net) => `local_net=${net}`),
      ''
    );
  } else {
    out.push('; [transport-wss] omitted: no TLS certificate configured', '');
  }

  for (const trunk of trunks) {
    const id = sectionName('trunk', trunk.name);
    const host = safe(trunk.host, 'example.invalid');
    const codecs = String(trunk.codecs || 'ulaw,alaw')
      .split(',')
      .map((c) => safe(c, 'ulaw'));
    out.push(
      `;[trunk] ${plain(trunk.name)} (${plain(trunk.provider)})`,
      `[${id}-registration]`,
      'type=registration',
      `outbound_auth=${id}-auth`,
      `server_uri=sip:${host}`,
      `client_uri=sip:${safe(trunk.username)}@${host}`,
      'retry_interval=60',
      'forbidden_retry_interval=600',
      'expiration=3600',
      '',
      `[${id}-auth]`,
      'type=auth',
      'auth_type=userpass',
      `username=${safe(trunk.username, trunk.name)}`,
      `password=${plain(trunk.secret)}`,
      '',
      `[${id}]`,
      'type=aor',
      `contact=sip:${host}`,
      'qualify_frequency=30',
      '',
      `[${id}-endpoint]`,
      'type=endpoint',
      `context=${safe(trunk.context, 'from-trunk')}`,
      `from_domain=${sipDomain()}`,
      'disallow=all',
      ...codecs.map((c) => `allow=${c}`),
      `outbound_auth=${id}-auth`,
      `aors=${id}`,
      trunk.from_user ? `from_user=${safe(trunk.from_user)}` : '',
      'direct_media=no',
      'rtp_symmetric=yes',
      'force_rport=yes',
      'rewrite_contact=yes',
      'timers=no',
      ...faxDetect(),
      '',
      `[${id}-identify]`,
      'type=identify',
      `endpoint=${id}-endpoint`,
      `match=${host}`,
      ''
    );
  }

  for (const ext of extensions) {
    // The endpoint is named after the extension itself. chan_pjsip identifies a
    // registration by the user part of the request (`res_pjsip_endpoint_identifier_user`),
    // so the name the phone registers as and the endpoint name have to be the
    // same string — a prefixed name means "no matching endpoint found".
    const id = safe(ext.extension, 'x');
    out.push(
      `;[extension] ${safe(ext.extension)} ${plain(ext.display_name)}`,
      `[${id}]`,
      'type=endpoint',
      'context=internal',
      `from_domain=${sipDomain()}`,
      'disallow=all',
      'allow=ulaw',
      'allow=alaw',
      `auth=${id}-auth`,
      `aors=${id}`,
      `callerid=${callerIdString(ext)}`,
      ext.voicemail ? `mailboxes=${safe(ext.extension)}@default` : '',
      'device_state_busy_at=2',
      '',
      `[${id}-auth]`,
      'type=auth',
      'auth_type=userpass',
      `username=${safe(ext.extension)}`,
      `password=${plain(ext.secret) || `change-me-${safe(ext.extension)}`}`,
      '',
      `[${id}]`,
      'type=aor',
      'max_contacts=3',
      'remove_existing=yes',
      'maximum_expiration=7200',
      ''
    );
  }

  // One WebRTC endpoint per extension, next to the desk-phone endpoint. A call
  // to the extension rings both, so an operator can answer in the browser and
  // the handset is not a separate number to remember.
  for (const ext of extensions) {
    const num = safe(ext.extension);
    const id = sectionName('webrtc', num);
    out.push(
      `;[softphone] ${num} ${plain(ext.display_name)} — DTLS-SRTP only`,
      `[${id}]`,
      'type=endpoint',
      'context=internal',
      `from_domain=${sipDomain()}`,
      'disallow=all',
      'allow=opus',
      'allow=ulaw',
      'allow=alaw',
      ...(config.softphone.video ? ['allow=vp8', 'allow=h264', 'max_video_streams=1'] : ['max_video_streams=0']),
      // `webrtc=yes` is the supported preset: ICE, AVPF, rtcp_mux and a
      // self-signed DTLS certificate. The explicit lines below are the parts we
      // never want a future Asterisk to default differently.
      'webrtc=yes',
      'media_encryption=dtls',
      'dtls_auto_generate_cert=yes',
      'media_use_received_transport=yes',
      'ice_support=yes',
      'rtcp_mux=yes',
      'use_avpf=yes',
      'timers=no',
      'direct_media=no',
      'rtp_symmetric=yes',
      'force_rport=yes',
      'rewrite_contact=yes',
      `auth=${id}-auth`,
      `aors=${id}`,
      `callerid=${callerIdString(ext)}`,
      ext.voicemail ? `mailboxes=${num}@default` : '',
      ...faxDetect(),
      '',
      `[${id}-auth]`,
      'type=auth',
      'auth_type=userpass',
      // The browser registers as `webrtc-<num>`, which is what makes chan_pjsip
      // match this endpoint rather than the desk-phone one.
      `username=${id}`,
      `password=${plain(ext.secret) || `change-me-${num}`}`,
      '',
      `[${id}]`,
      'type=aor',
      'max_contacts=2',
      'remove_existing=yes',
      'maximum_expiration=3600',
      ''
    );
  }

  return out.filter((line) => line !== undefined).join('\n');
}

/**
 * chan_pjsip will hand a call to the `fax` extension when the far end starts a
 * T.38 session — that is what turns an ordinary voice DID into one that also
 * receives faxes. The dialplan's `fax` extension is the landing point.
 */
const faxDetect = () => (config.fax.enabled ? ['faxdetect=incoming'] : []);

/** Both endpoints of one extension, for a parallel ring. */
const ringTargets = (num) => `PJSIP/${safe(num)}&PJSIP/${sectionName('webrtc', num)}`;

/** Where the switch keeps received documents and outbound staging files. */
export const faxDir = () => String(config.fax.dir || join(config.dataDir, 'faxes')).replace(/\/+$/, '');

function faxConf() {
  return [
    '; generated by telno — do not edit, changes are overwritten on apply',
    '[general]',
    `minrate=${config.fax.minRate}`,
    `maxrate=${config.fax.maxRate}`,
    // Without status events a send has no result to report, so the console could
    // only guess whether the other machine printed anything.
    'statusevents=yes',
    '',
  ].join('\n');
}

/**
 * The receiving half of fax: answer, hand the line to res_fax, and leave a
 * receipt the platform can read.
 *
 * A status file rather than an API call is deliberate. The dialplan has no way
 * to call back into Node, and polling a file the switch wrote is the one path
 * that still works when the API is restarting. Every value is quoted because a
 * caller ID is attacker-controlled input reaching a shell.
 */
function faxContexts() {
  const dir = faxDir();
  const status = `${dir}/status`;
  const inbox = `${dir}/in`;
  return [
    ';[fax] received documents land on the data volume, in the store the console reads',
    '[telno-fax-in]',
    'exten => s,1,NoOp(Inbound fax from ${CALLERID(num)} to ${TELNO_DID})',
    ' same => n,Answer()',
    ' same => n,Wait(1)',
    ' same => n,Set(FAXOPT(ecm)=yes)',
    ` same => n,Set(FAXOPT(maxrate)=${config.fax.maxRate})`,
    ` same => n,Set(FAXOPT(minrate)=${config.fax.minRate})`,
    ` same => n,Set(FAXOPT(stationid)=${safe(config.fax.stationId, 'Telno')})`,
    ` same => n,ReceiveFax(${inbox}/\${UNIQUEID}.tif)`,
    ' same => n,Set(FAX_RESULT=${FAXOPT(status)})',
    ' same => n,Set(FAX_PAGES=${FAXOPT(pages)})',
    ` same => n,System(printf '%s|%s|%s|%s|%s\\n' "\${UNIQUEID}" "\${FAX_RESULT}" "\${FAX_PAGES}" "\${CALLERID(num)}" "\${TELNO_DID}" > ${status}/\${UNIQUEID}.done)`,
    ' same => n,Hangup()',
    '',
  ];
}

function dialplan(extensions, trunks, flows, dids, agentPolicy = new Map(), parkedLines = new Set()) {
  const trunkEndpoint = trunks[0] ? `${sectionName('trunk', trunks[0].name)}-endpoint` : '';
  const recDir = String(config.softphone.recordingDir || '/data/recordings').replace(/\/+$/, '');
  // The third MixMonitor argument is a comment written into the file's metadata,
  // so it stays ASCII and comma-free: dialplan arguments are not quoted here.
  const record = (why) => `MixMonitor(${recDir}/\${UNIQUEID}.wav,b,${safe(why, 'recording').slice(0, 40)})`;
  const policyFor = (agent) => ({
    inbound: !!agent?.record_inbound,
    outbound: !!agent?.record_outbound,
    label: agent ? plain(agent.name) : '',
  });
  // Outbound calls are the same pattern for every caller, so the policy is
  // resolved at dial time from the calling extension's own number.
  const outboundRecording = extensions
    .map((ext) => ({ ext, agent: ext.number_id ? agentPolicy.get(ext.number_id) : null }))
    .map(({ ext, agent }) => ({ ext, policy: policyFor(agent) }))
    .filter(({ ext, policy }) => policy.outbound && !ext.scif);

  const out = [
    '; generated by telno — do not edit, changes are overwritten on apply',
    '',
    '[general]',
    'static=yes',
    'writeprotect=no',
    'clearglobalvars=no',
    '',
    '[globals]',
    `TRUNK=${trunkEndpoint}`,
    '',
    '[internal]',
  ];

  for (const ext of extensions) {
    const num = safe(ext.extension);
    const actions = [`NoOp(Call ${'${CALLERID(num)}'} -> ${num})`, `Set(__TELNO_EXT=${num})`];
    if (ext.dnd === 1) {
      actions.push(`VoiceMail(${num}@default,b)`);
    } else if (ext.forward_to) {
      actions.push(`Goto(internal,${safe(ext.forward_to)},1)`);
    } else if (parkedLines.has(num)) {
      // The line has a phone registered for calls, so an unanswered call is
      // parked rather than given up on: the desk phone and any open browser ring
      // first, then the caller waits in a slot whose number the push carries, so
      // the app can dial it and be bridged. If nobody retrieves it, the parking
      // lot hands the call to `telno-comeback` below.
      actions.push(
        `Set(__TELNO_PARK_EXT=${num})`,
        `Set(CHANNEL(parkinglot)=${parkingLot()})`,
        `Dial(${ringTargets(num)},${config.parking.ringSeconds},tT)`,
        'Park()'
      );
    } else {
      // Ring the handset and the browser together: the WebRTC endpoint is the
      // same extension, so an operator answers wherever they are. Dialing only
      // the desk endpoint alone would leave a browser-only extension unreachable.
      actions.push(
        `Dial(${ringTargets(num)},25,tT)`
      );
      if (ext.voicemail) actions.push(`VoiceMail(${num}@default,u)`);
    }
    actions.push('Hangup()');
    out.push(
      ...actions.map((action, index) => `${index === 0 ? 'exten' : ' same'} => ${index === 0 ? num + ',1,' : 'n,'}${action}`),
      ''
    );
  }

  // Generic internal dialing for anything shaped like an extension. The
  // endpoint names are namespaced, so the pattern has to build them; a bare
  // `PJSIP/${EXTEN}` would ask for an endpoint that never exists.
  out.push(
    'exten => _1XX,1,Dial(PJSIP/${EXTEN}&PJSIP/webrtc-${EXTEN},25,tT)',
    ' same => n,Hangup()',
    ''
  );

  // Retrieving a parked call. The phone that answered CallKit comes forward,
  // registers its WebRTC endpoint like any other session, and dials the slot the
  // push named — that dial is what bridges it to the waiting caller.
  if (parkedLines.size) {
    out.push(
      ';[parking] dial a space to take the call waiting in it',
      'exten => _7XXX,1,NoOp(Retrieve parked call ${EXTEN})',
      ` same => n,ParkedCall(\${EXTEN}@${parkingLot()})`,
      ' same => n,Hangup()',
      ''
    );
  }

  // IVR entry points live in `internal`; their menus live in their own context
  // so pressing "1" means something different in each flow.
  for (const flow of flows) {
    let options = [];
    try {
      options = JSON.parse(flow.options || '[]');
    } catch {
      options = [];
    }
    const num = safe(flow.extension);
    const menu = `ivr-${num}`;

    out.push(
      `;[ivr] ${plain(flow.name)}`,
      `exten => ${num},1,Answer()`,
      ' same => n,Wait(1)',
      ` same => n,Background(custom/telno-${num})`,
      ' same => n,WaitExten(4)',
      ` same => n,Goto(${menu},t,1)`,
      ''
    );

    out.push(`[${menu}]`);
    for (const option of options) {
      const digit = safe(option.digit, '').slice(0, 1);
      if (!digit) continue;
      out.push(
        `exten => ${digit},1,NoOp(IVR ${plain(flow.name)} option ${digit})`,
        ` same => n,Goto(internal,${safe(option.target, 's')},1)`
      );
    }
    out.push(
      'exten => i,1,Playback(pbx-invalid)',
      ` same => n,Goto(internal,${num},1)`,
      `exten => t,1,${flow.timeout_dest ? `Goto(internal,${safe(flow.timeout_dest)},1)` : 'Playback(vm-goodbye)'}`,
      ' same => n,Hangup()',
      ''
    );
  }

  out.push(
    '[from-trunk]',
    'exten => _+X.,1,NoOp(Inbound ${CALLERID(num)} -> ${EXTEN})',
    ' same => n,Goto(registry,${EXTEN},1)',
    ' same => n,Hangup()',
    'exten => _X.,1,Goto(registry,${EXTEN},1)',
    ' same => n,Hangup()',
    '',
    '[from-internal]',
    'exten => _X.,1,Goto(internal,${EXTEN},1)',
    'exten => _+X.,1,Goto(outbound,${EXTEN},1)',
    ''
  );

  out.push('[registry]');
  if (dids.length) {
    for (const did of dids) {
      const digits = String(did.e164).replace(/\D/g, '');
      const agent = agentPolicy.get(did.number_id);
      const policy = policyFor(agent);
      // A SCIF line is never recorded, whatever the agent's policy says. The
      // dialplan is where recording actually happens, so this is the check that
      // matters — a console badge is not a guarantee.
      const inboundScif = extensions.some((ext) => ext.scif && String(ext.extension) === String(did.extension));
      // Recording is a policy decision made in the console, so it has to reach
      // the switch: no dialplan line means no recording, whatever the UI says.
      const recordLines = policy.inbound && !inboundScif
        ? [
            ` same => n,Set(__TELNO_AGENT=${safe(agent.name, 'agent')})`,
            ` same => n,${record(`inbound-${safe(agent.name, 'agent')}`)}`,
          ]
        : [];
      const target = did.fax_mode === 'fax' && config.fax.enabled
        ? 'telno-fax-in'
        : `internal,${safe(did.extension)}`;
      out.push(
        `exten => ${digits},1,NoOp(${plain(did.display_name)} <- ${plain(did.e164)})`,
        ` same => n,Set(__TELNO_DID=${plain(did.e164)})`,
        ...(did.fax_mode === 'fax' && config.fax.enabled ? [] : recordLines),
        ` same => n,Goto(${target.includes(',') ? target : `${target},s`},1)`,
        `exten => _+${digits},1,Goto(${target.includes(',') ? target : `${target},s`},1)`
      );
    }
    if (agentPolicy.size) {
      const named = [...agentPolicy.values()].map((agent) => plain(agent.name)).join(', ');
      out.push(`; voice agent policy in force for: ${named}`);
    }
  } else {
    out.push('; no DIDs are assigned to extensions yet');
  }
  // A terminal that negotiates T.38 mid-call is a fax machine, not a caller:
  // chan_pjsip moves it here, and the receiver takes over.
  if (config.fax.enabled) {
    out.push('exten => fax,1,NoOp(Fax detected from ${CALLERID(num)})', ' same => n,Goto(telno-fax-in,s,1)', '');
  }
  out.push('exten => s,1,Answer()', ' same => n,Wait(1)', ' same => n,Playback(ss-noservice)', ' same => n,Hangup()', '');

  if (config.fax.enabled) {
    out.push(...faxContexts());
  }

  out.push('[outbound]');
  if (trunks.length) {
    if (extensions.some((ext) => ext.scif)) {
    out.push(
      `; SCIF lines never record: ${extensions
        .filter((ext) => ext.scif)
        .map((ext) => safe(ext.extension))
        .join(', ')}`,
      ''
    );
  }
  const outRecord = outboundRecording.length
      ? [
          ' same => n,Set(__TELNO_RECORD_OUT=0)',
          ...outboundRecording.map(
            ({ ext }) =>
              ` same => n,ExecIf($["\${CALLERID(num)}"="${safe(ext.extension)}"]?Set(__TELNO_RECORD_OUT=1))`
          ),
          ` same => n,ExecIf($["\${TELNO_RECORD_OUT}"="1"]?${record('outbound')})`,
        ]
      : [];
    if (outboundRecording.length) {
      out.push(
        `; outbound recording follows the agent policy for: ${outboundRecording
          .map(({ ext, policy }) => `${safe(ext.extension)} (${policy.label})`)
          .join(', ')}`
      );
    }
    out.push(
      'exten => _+X.,1,NoOp(Outbound ${CALLERID(num)} -> ${EXTEN})',
      ...outRecord,
      ` same => n,Dial(PJSIP/\${EXTEN}@${trunkEndpoint},60,tT)`,
      ' same => n,Congestion()',
      ' same => n,Hangup()'
    );
  } else {
    out.push('exten => _+X.,1,NoOp(No trunk configured)', ' same => n,Playback(ss-noservice)', ' same => n,Hangup()');
  }
  out.push('');

  // A parked call nobody retrieved comes back here instead of into the dialplan:
  // the line's own voicemail answers, so parking costs the caller a wait and
  // nothing else.
  if (parkedLines.size) {
    out.push(
      ';[parking] nobody picked the parked call up: the line\'s voicemail answers',
      '[telno-comeback]',
      'exten => s,1,NoOp(Parked call was not retrieved)',
      ' same => n,GotoIf($["${TELNO_PARK_EXT}"=""]?unaddressed)',
      ' same => n,VoiceMail(${TELNO_PARK_EXT}@default,u)',
      ' same => n,Hangup()',
      'exten => unaddressed,1,Playback(vm-goodbye)',
      ' same => n,Hangup()',
      ''
    );
  }

  return out.join('\n');
}

const parkingLot = () => safe(config.parking.lot, 'telno');

/**
 * The parking lot, in res_parking's own language.
 *
 * A slot is a numbered extension, which is the whole point: the app does not
 * need a special protocol to take a waiting call, it dials 7001 like any other
 * number. `parkingtime` is how long the caller waits before `telno-comeback`
 * hands them to the line's voicemail, and `comebackdialtime=0` keeps them from
 * being returned to a desk phone that already failed to answer.
 */
function parking() {
  const start = Math.min(config.parking.start, config.parking.end);
  const end = Math.max(config.parking.start, config.parking.end);
  return [
    '; generated by telno — do not edit, changes are overwritten on apply',
    '[general]',
    '',
    `[${parkingLot()}]`,
    // The spaces. res_parking calls the range `parkpos`; `parking_start` is not
    // an option this switch accepts, and a rejected file means no parking at all.
    `parkpos=${start}-${end}`,
    `parkingtime=${config.parking.timeoutSeconds}`,
    // Back to the line's own voicemail, not to the desk phone that has already
    // failed to answer: comebackdialtime=0 is what makes that immediate.
    'comebacktoorigin=no',
    'comebackcontext=telno-comeback',
    'comebackdialtime=0',
    `parkedmusicclass=${config.parking.mohClass}`,
    // Lowest free space, so the slot announced and the slot pushed are the same.
    'findslot=first',
    // The waiting caller hears music; whoever retrieves hears nothing extra.
    'parkedplay=caller',
    // The caller may transfer a parked call on and re-park it; the retriever may
    // not, so a slot cannot be left occupied by somebody else's handoff.
    'parkedcalltransfers=caller',
    'parkedcallreparking=caller',
    'parkedcallhangup=caller',
    'parkedcallrecording=caller',
    '',
  ].join('\n');
}

function voicemail(extensions) {
  const lines = [
    '; generated by telno',
    '',
    '[general]',
    'format=wav',
    'serveremail=voicemail@localhost',
    'attach=no',
    'maxmsg=100',
    'maxsecs=180',
    'saycid=yes',
    'review=yes',
    '',
    '[default]',
  ];
  const withVm = extensions.filter((e) => e.voicemail);
  if (!withVm.length) lines.push('; no voicemail boxes configured');
  for (const ext of withVm) {
    lines.push(`${safe(ext.extension)} => ${plain(ext.email) || 'voicemail@localhost'},${plain(ext.display_name)}`);
  }
  return lines.join('\n') + '\n';
}


/**
 * The switch needs a certificate before it can listen on WSS. Generate a
 * self-signed one on first apply so a fresh container has a working softphone
 * without an operator running openssl by hand; a real certificate is expected
 * in production (SOFTPHONE_TLS_CERT / SOFTPHONE_TLS_KEY).
 */
export function ensureTlsMaterial() {
  const dir = config.telephony.configDir || config.dataDir;
  const paths = tlsPaths();
  if (!dir || !paths.cert || !paths.key) {
    return { ok: false, reason: 'no TLS paths configured' };
  }
  if (paths.ready) return { ok: true, generated: false, cert: paths.cert, key: paths.key };

  const keyDir = join(dir, 'keys');
  mkdirSync(keyDir, { recursive: true });
  const host = (() => {
    try {
      return new URL(config.publicUrl).hostname;
    } catch {
      return 'localhost';
    }
  })();
  const args = [
    'req', '-x509', '-newkey', 'rsa:2048', '-sha256', '-days', '825', '-nodes',
    '-keyout', paths.key,
    '-out', paths.cert,
    '-subj', '/CN=telno',
    '-addext', `subjectAltName=DNS:${host},DNS:localhost,IP:127.0.0.1`,
  ];
  let result = spawnSync('openssl', args, { encoding: 'utf8' });
  if (result.error || result.status !== 0) {
    // `-addext` needs OpenSSL 1.1.1+; retry without it rather than fail.
    result = spawnSync('openssl', args.filter((a) => a !== '-addext' && !a.startsWith('subjectAltName')), {
      encoding: 'utf8',
    });
  }
  if (result.error || result.status !== 0) {
    return { ok: false, reason: 'openssl unavailable', detail: (result.stderr || result.error?.message || '').slice(0, 200) };
  }
  // The switch and this process run as the same unprivileged user in the
  // container, so the key only needs to be readable by its owner. Group read is
  // kept for a deployment that runs Asterisk as a separate account, where a
  // root-only chown is the one thing that can fix ownership.
  for (const file of [paths.cert, paths.key]) {
    try {
      chmodSync(file, 0o640);
    } catch {
      /* the volume may already carry the right mode */
    }
    if (typeof process.getuid === 'function' && process.getuid() === 0) {
      spawnSync('chown', [`${config.telephony.runAs || 'telno'}:${config.telephony.runAs || 'telno'}`, file], {
        stdio: 'ignore',
      });
    }
  }
  return { ok: true, generated: true, cert: paths.cert, key: paths.key };
}

/** Fingerprint of the listener certificate, shown in the console for pinning. */
export function tlsFingerprint() {
  const { cert, ready } = tlsPaths();
  if (!ready) return null;
  try {
    const pem = readFileSync(cert, 'utf8');
    const body = pem.replace(/-----[^-]+-----/g, '').replace(/\s+/g, '');
    return createHash('sha256').update(Buffer.from(body, 'base64')).digest('hex');
  } catch {
    return null;
  }
}

/** Write the generated files where Asterisk reads them. */
export function writeConfigs() {
  if (!config.telephony.configDir) {
    return { written: false, reason: 'ASTERISK_CONFIG_DIR not set' };
  }
  mkdirSync(config.telephony.configDir, { recursive: true });
  if (config.fax.enabled) {
    // The switch writes here as its own user; the platform reads what it leaves.
    for (const sub of ['in', 'out', 'status']) mkdirSync(join(faxDir(), sub), { recursive: true });
  }
  const tls = ensureTlsMaterial();
  const files = generateConfigs();
  for (const [name, content] of Object.entries(files)) {
    writeFileSync(join(config.telephony.configDir, name), content, 'utf8');
  }
  return {
    written: true,
    dir: config.telephony.configDir,
    files: Object.keys(files),
    softphone: { tls: tls.ok, generated: !!tls.generated, reason: tls.reason || null },
  };
}
